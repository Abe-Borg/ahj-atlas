const ORIGINAL='ORIGINAL_ASSIGNMENT';
async function setup(t){
  const dir=mkdtempSync(path.join(os.tmpdir(),'ahj-rename-test-'));
  const app=await createApp({dataDir:dir,port:0,provider:new FakeProvider(),worker:false});
  t.after(async()=>{await app.close();assert.ok(path.resolve(dir).startsWith(path.join(os.tmpdir(),'ahj-rename-test-')));rmSync(dir,{recursive:true,force:true});});
  const {token}=await(await fetch(app.url+'/api/bootstrap')).json();
  const rename=(id,name)=>fetch(app.url+'/api/projects/'+id+'/rename',{method:'POST',headers:{'Content-Type':'application/json','X-App-Token':token},body:JSON.stringify({name})});
  return {app,rename,token};
}
function runningResearch(store,project){
  const payload={model:'claude-sonnet-5-5',messages:[{role:'user',content:ORIGINAL}],tools:[{name:'web_search',max_uses:2}]};
  store.updateProject(project.id,{status:'researching',note:'Jurisdiction research is in progress.'});
  store.updateStage(project.id,'jurisdiction',{status:'running',rounds:1,output:'Saved jurisdiction brief.',messages:[{role:'user',content:ORIGINAL}]});
  const attempt=store.reserve(project.id,'jurisdiction',{mode:'realtime',modelKey:'research',payload,reserve:250000});
  store.updateAttempt(attempt.id,{state:'pending'});
  return store.attempt(attempt.id);
}

test('renaming after research starts updates every stored label and leaves the running request alone',async t=>{
  const {app,rename}=await setup(t),s=app.store,p=s.create(input),other=s.create({...input,name:'Leave this project'});
  const attempt=runningResearch(s,p),before=s.project(p.id);
  const stages=s.stages(p.id),reportBody=before.report,note=before.note;
  const next='  Westside pump room  ';
  const saved=s.renameProject(p.id,next);
  assert.equal(saved.name,'Westside pump room');
  assert.equal(saved.input.name,'Westside pump room');
  assert.equal(saved.status,'researching');
  assert.equal(saved.note,note);
  assert.equal(saved.address,before.address);
  assert.equal(saved.input.address,before.input.address);
  assert.equal(saved.input.discipline,before.input.discipline);
  assert.equal(saved.input.siteDescription,before.input.siteDescription);
  assert.equal(saved.cancel_requested,false);
  assert.equal(saved.report,reportBody);
  assert.equal(saved.cost,before.cost);
  assert.deepEqual(s.stages(p.id),stages);
  assert.deepEqual(s.attempt(attempt.id).payload,attempt.payload);
  assert.equal(s.attempt(attempt.id).state,'pending');
  assert.equal(s.project(other.id).name,'Leave this project');
  const reused=researchPayload(s,s.project(p.id),s.stage(p.id,'jurisdiction'));
  assert.equal(reused.messages[0].content,ORIGINAL);
  assert.ok(!JSON.stringify(reused).includes('Westside pump room'));
  const upcoming=JSON.stringify(researchPayload(s,s.project(p.id),s.stage(p.id,'contacts')));
  assert.match(upcoming,/Westside pump room/);
  assert.equal(projectSection(s,p.id,'context').name,'Westside pump room');
  assert.equal(projectSection(s,p.id,'context').input.name,'Westside pump room');
  assert.equal(projectSection(s,p.id,'context').status,'researching');
  const activity=s.events(p.id).find(e=>e.kind==='rename');
  assert.match(activity.message,/from “Workflow verification · synthetic data” to “Westside pump room”/);
  const diagnostics=JSON.stringify(diagnosticReport(s,{connection:{}}));
  assert.match(diagnostics,/Project name changed\. The names are omitted from diagnostics\./);
  assert.ok(!diagnostics.includes('Westside pump room'));
  assert.equal(s.renameProject(p.id,'Westside pump room').updated,saved.updated);
  assert.equal(s.events(p.id).filter(e=>e.kind==='rename').length,1);
  const response=await rename(p.id,'  Café pump room  ');
  assert.equal(response.status,200);
  const body=await response.json();
  assert.equal(body.name,'Café pump room');
  assert.equal(body.input.name,'Café pump room');
  assert.equal(body.status,'researching');
  const detail=await(await fetch(app.url+'/api/projects/'+p.id)).json();
  assert.equal(detail.project.name,'Café pump room');
  assert.equal(detail.project.input.name,'Café pump room');
  assert.equal(detail.stages.find(stage=>stage.id==='jurisdiction').status,'running');
  assert.match(detail.events[0].message,/Café pump room/);
  const listed=await(await fetch(app.url+'/api/projects')).json();
  assert.equal(listed.find(item=>item.id===p.id).name,'Café pump room');
  assert.equal(listed.find(item=>item.id===p.id).input.name,'Café pump room');
  const exported=await fetch(app.url+'/api/projects/'+p.id+'/export?format=json');
  assert.equal(exported.status,200);
  const filename=decodeURIComponent(exported.headers.get('content-disposition').match(/filename\*=UTF-8''([^;]+)/)[1]);
  assert.match(filename,/^Café pump room - AHJ research\.json$/);
  const data=await exported.json();
  assert.equal(data.project.name,'Café pump room');
  assert.equal(data.project.context.name,'Café pump room');
  assert.equal(data.report,null);
  assert.deepEqual(s.attempt(attempt.id).payload,attempt.payload);
});

