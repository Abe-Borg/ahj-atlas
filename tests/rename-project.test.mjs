test('rename uses the same name rules and does not partially write',async t=>{
  const {app,rename}=await setup(t),s=app.store,p=s.create(input);
  runningResearch(s,p);
  for(const name of [undefined,'','   ','\n','x'.repeat(101),'Unsafe\nname']){
    assert.throws(()=>s.renameProject(p.id,name),/project name/);
    assert.equal((await rename(p.id,name)).status,400);
    assert.equal(s.project(p.id).name,input.name);
    assert.equal(s.project(p.id).input.name,input.name);
  }
  assert.equal((await fetch(app.url+'/api/projects/'+p.id+'/rename',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({name:'Nope'})})).status,403);
  assert.equal((await rename('00000000-0000-4000-8000-000000000000','Nope')).status,404);
  assert.equal(s.project(p.id).status,'researching');
  s.db.exec("CREATE TRIGGER prevent_rename BEFORE UPDATE ON projects BEGIN SELECT RAISE(ABORT,'Test failure'); END;");
  assert.throws(()=>s.renameProject(p.id,'Should not stick'));
  assert.equal(s.project(p.id).name,input.name);
  assert.equal(s.events(p.id).some(e=>e.kind==='rename'),false);
  s.db.exec('DROP TRIGGER prevent_rename');
  assert.equal(s.renameProject(p.id,'Should stick').name,'Should stick');
});

test('the project page can rename while research is running and after it is finished',async t=>{
  const dir=mkdtempSync(path.join(os.tmpdir(),'ahj-rename-ui-'));
  const app=await createApp({dataDir:dir,port:0,provider:new FakeProvider(),worker:false});
  let browser;
  t.after(async()=>{await browser?.close();await app.close();rmSync(dir,{recursive:true,force:true});});
  const s=app.store,running=s.create({...input,name:'Running synthetic project'}),finished=s.create({...input,name:'Finished synthetic project'});
  const attempt=runningResearch(s,running);
  const finishedReport=report();finishedReport.summary='Finished synthetic report body';
  s.updateProject(finished.id,{status:'complete',report:finishedReport});
  for(const stage of s.stages(finished.id))s.updateStage(finished.id,stage.id,{status:'complete',output:'Saved'});
  browser=await puppeteer.launch({executablePath:browserPath(),headless:true,pipe:true,args:process.platform==='linux'?['--no-sandbox']:[],env:{...process.env,XDG_CONFIG_HOME:path.join(dir,'config')}});
  const page=await browser.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const click=selector=>page.evaluate(sel=>document.querySelector(sel).click(),selector);
  await page.setViewport({width:1440,height:1000});
  await page.goto(app.url+'/#project='+encodeURIComponent(running.id));
  await page.waitForSelector('#project-name');
  assert.equal(await page.$eval('#project-name',e=>e.disabled),false);
  assert.equal(await page.$eval('#project-name',e=>e.value),'Running synthetic project');
  assert.equal(await page.$eval('#save-project-name',e=>e.disabled),true);
  assert.equal(await page.$eval('#cancel-research',e=>e.textContent),'Stop research');
  await page.focus('#project-name');
  await page.keyboard.press('End');
  await page.keyboard.type(' draft');
  s.updateProject(running.id,{note:'Synthetic progress update.'});
  await page.waitForFunction(()=>document.querySelector('.notice')?.textContent.includes('Synthetic progress update.'),{timeout:10000});
  assert.equal(await page.$eval('#project-name',e=>e.value),'Running synthetic project draft');
  assert.equal(await page.evaluate(()=>document.activeElement.id),'project-name');
  await page.setRequestInterception(true);
  let rejectSave=true;
  page.on('request',req=>{if(rejectSave&&req.url().endsWith('/rename')&&req.method()==='POST'){rejectSave=false;req.respond({status:400,contentType:'application/json',body:JSON.stringify({error:'Synthetic rename failure. Please retry.'})});}else req.continue();});
  await click('#save-project-name');
  await page.waitForFunction(()=>document.querySelector('#rename-error')?.textContent.includes('Synthetic rename failure'));
  assert.equal(await page.$eval('#project-name',e=>e.value),'Running synthetic project draft');
  assert.equal(s.project(running.id).name,'Running synthetic project');
  await click('#save-project-name');
  await page.waitForFunction(()=>document.querySelector('#toast')?.textContent==='Project name saved.');
  assert.equal(s.project(running.id).name,'Running synthetic project draft');
  assert.equal(s.project(running.id).input.name,'Running synthetic project draft');
  assert.equal(s.project(running.id).status,'researching');
  assert.equal(s.stage(running.id,'jurisdiction').status,'running');
  assert.equal(s.stage(running.id,'jurisdiction').output,'Saved jurisdiction brief.');
  assert.deepEqual(s.attempt(attempt.id).payload,attempt.payload);
  assert.equal(s.attempt(attempt.id).state,'pending');
  assert.equal(await page.$eval(`[data-project="${running.id}"] strong`,e=>e.textContent),'Running synthetic project draft');
  await click('[data-tab=chat]');
  await page.waitForSelector('.chat-heading h2');
  assert.match(await page.$eval('.chat-heading h2',e=>e.textContent),/Running synthetic project draft/);
  await click('[data-tab=activity]');
  await page.waitForFunction(()=>document.querySelector('.activity')?.textContent.includes('Project renamed from “Running synthetic project” to “Running synthetic project draft”'));
  assert.match(await page.$eval('.activity',e=>e.textContent),/Project renamed from “Running synthetic project” to “Running synthetic project draft”/);
  await click(`[data-project="${finished.id}"]`);
  await page.waitForFunction(()=>document.querySelector('#project-name')?.value==='Finished synthetic project');
  assert.equal(await page.$eval('#project-name',e=>e.disabled),false);
  await page.$eval('#project-name',e=>{e.value='Finished label';e.dispatchEvent(new Event('input',{bubbles:true}));});
  await click('#save-project-name');
  await page.waitForFunction(()=>document.querySelector('#project-name')?.value==='Finished label');
  assert.equal(s.project(finished.id).status,'complete');
  assert.equal(s.project(finished.id).report.summary,'Finished synthetic report body');
  assert.ok(s.stages(finished.id).every(stage=>stage.status==='complete'));
  await page.setViewport({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  assert.deepEqual(errors,[]);
  assert.equal(app.services.engine.running.size,0);
});
